// Generates src/lib/kibb/schema.ts (TypeScript types for every schema in the kibb.io OpenAPI spec).
//
//   curl -s https://tradewinds.kibb.io/api-docs/openapi.json -o docs/kibb-openapi.json
//   node scripts/gen-kibb-schema.mjs
//
// Covers the JSON Schema the spec uses: $ref, objects, arrays, enums, oneOf/anyOf/allOf,
// nullable type lists and additionalProperties.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(readFileSync(join(root, "docs/kibb-openapi.json"), "utf8"));
const schemas = spec.components.schemas;

const PRIM = { string: "string", integer: "number", number: "number", boolean: "boolean", null: "null" };
const ident = /^[A-Za-z_$][\w$]*$/;

function doc(text, indent) {
  if (!text) return "";
  const lines = String(text).trim().replace(/\*\//g, "*\\/").split("\n");
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`;
  return `${indent}/**\n${lines.map((l) => `${indent} * ${l}`.trimEnd()).join("\n")}\n${indent} */\n`;
}

function union(parts) {
  const uniq = [...new Set(parts)];
  return uniq.length === 1 ? uniq[0] : uniq.map((p) => (p.includes("=>") ? `(${p})` : p)).join(" | ");
}

function ts(s, indent = "") {
  if (!s || typeof s !== "object" || Object.keys(s).filter((k) => k !== "description").length === 0) return "unknown";
  if (s.$ref) return s.$ref.split("/").pop();
  if (s.enum) return union(s.enum.map((v) => JSON.stringify(v)));
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.oneOf || s.anyOf) return union((s.oneOf ?? s.anyOf).map((x) => ts(x, indent)));
  if (s.allOf) return s.allOf.map((x) => ts(x, indent)).join(" & ");
  const types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : s.properties ? ["object"] : [];
  if (types.length > 1) return union(types.map((t) => ts({ ...s, type: t }, indent)));
  const t = types[0];
  if (t === "array") {
    const inner = ts(s.items, indent);
    return /[ |&]/.test(inner) ? `Array<${inner}>` : `${inner}[]`;
  }
  if (t === "object") {
    const props = s.properties ?? {};
    const req = new Set(s.required ?? []);
    const inner = indent + "  ";
    const body = Object.entries(props)
      .map(([k, v]) => `${doc(v.description, inner)}${inner}${ident.test(k) ? k : JSON.stringify(k)}${req.has(k) ? "" : "?"}: ${ts(v, inner)};`)
      .join("\n");
    const extra = s.additionalProperties && typeof s.additionalProperties === "object" ? ts(s.additionalProperties, inner) : s.additionalProperties === true ? "unknown" : null;
    if (!body) return extra ? `Record<string, ${extra}>` : "Record<string, unknown>";
    return `{\n${body}${extra ? `\n${inner}[key: string]: ${extra};` : ""}\n${indent}}`;
  }
  return PRIM[t] ?? "unknown";
}

let out = `// Generated by scripts/gen-kibb-schema.mjs from docs/kibb-openapi.json (${spec.info.title} ${spec.info.version}). Do not edit.
// Every schema the API defines, by its spec name. Import as: import type * as S from "@/lib/kibb/schema".

`;
for (const name of Object.keys(schemas).sort()) {
  const s = schemas[name];
  const body = ts(s);
  out += doc(s.description, "");
  out += body.startsWith("{\n") ? `export interface ${name} ${body}\n\n` : `export type ${name} = ${body};\n\n`;
}
writeFileSync(join(root, "src/lib/kibb/schema.ts"), out);
console.log(`wrote ${Object.keys(schemas).length} schemas to src/lib/kibb/schema.ts`);
